// The catalog the guess box types against: real companies, real tickers, one
// plain sector word each, and the household names people actually say.
//
// It is written from knowledge rather than fetched, so it never needs a network
// and never drifts under the game. Two rules keep it honest and keep the
// typeahead unambiguous:
//
//   1. every company in the puzzle pool appears here with exactly the ticker
//      and sector string the pool uses, so picking a suggestion always solves
//      the puzzle it names
//   2. no ticker appears twice, and no alias belongs to two companies
//
// tools/guessSim.ts enforces both. Sector words are the same small vocabulary
// the pool uses, all lower case, because the easy mode tag compares them.
//
// Rows are [name, ticker, ...aliases]. An alias is only needed where the name a
// player would type differs from the legal name: alphabet takes google and
// goog, meta takes facebook and fb. Order inside a sector runs roughly from the
// famous to the obscure, and the typeahead breaks ties by that order, so a
// player typing g meets Alphabet before Grand Canyon Education.
//
// Companies that no longer trade are kept: they are half the fun of a market
// quiz, and their tickers are the ones they carried.

